    /** 이 지역의 대표 지점. 표에 없으면 null. */
    fun pointOf(region: String): Point? = COORDS[region.trim()]

    /** 좌표를 아는 두 지역 사이의 대권 거리(km). 한쪽이라도 표에 없으면 null. */
    fun distanceKm(a: String, b: String): Double? {
        val from = COORDS[a.trim()] ?: return null
        val to = COORDS[b.trim()] ?: return null
        return haversine(from.lat, from.lon, to.lat, to.lon)
    }

    private fun haversine(lat1: Double, lon1: Double, lat2: Double, lon2: Double): Double {
        val dLat = Math.toRadians(lat2 - lat1)
        val dLon = Math.toRadians(lon2 - lon1)
        val h = sin(dLat / 2) * sin(dLat / 2) +
            cos(Math.toRadians(lat1)) * cos(Math.toRadians(lat2)) * sin(dLon / 2) * sin(dLon / 2)
        return 2 * EARTH_RADIUS_KM * asin(min(1.0, sqrt(h)))
    }
