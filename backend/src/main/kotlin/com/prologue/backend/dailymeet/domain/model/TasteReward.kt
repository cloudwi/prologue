package com.prologue.backend.dailymeet.domain.model

/**
 * 취향 카드를 넘긴 보람 — [EVERY]장마다 **오늘의 상대가 한 명 더 도착한다**.
 *
 * 보상은 재화가 아니라 사람이다(유저 결정 2026-09-02). 잉크는 결국 사람을 만나려고 쓰는 것이고,
 * 카드가 하는 일도 "누구를 만날지 더 잘 고르는 것"이라 보상과 행동이 같은 방향을 가리킨다.
 * 잉크로 주면 카드가 재화를 캐는 자리가 되고, 값싼 잉크가 글의 값어치까지 끌어내린다.
 *
 * **끝이 있는 이정표(10·30·60·100장)를 쓰다가 되풀이되는 규칙으로 바꿨다.** 카드 더미는 계속
 * 늘어날 것이라(운영이 새 카드를 붓는다) 끝을 못 박으면 100장을 넘긴 사람에게는 다시 아무것도
 * 남지 않는다. 늘어나는 더미에는 늘어나는 규칙이 맞다.
 *
 * 대신 [DAILY_LIMIT]으로 하루치를 묶는다. 되풀이되는 보상에 상한이 없으면 하루에 백 장을 넘겨
 * 열 명을 받아 갈 수 있고, 사람이 적은 지금 그건 후보 풀을 하루 만에 비우는 일이다.
 * 하루 한 번이면 "매일 조금씩 넘기는 사람"이 가장 많이 받는다 — 그게 우리가 바라는 습관이다.
 */
object TasteReward {

    /** 이만큼 넘길 때마다 상대 한 명. */
    const val EVERY = 10

    /** 하루에 이 규칙으로 받을 수 있는 최대 횟수(서비스 하루 기준, [ServiceDay]). */
    const val DAILY_LIMIT = 1

    /**
     * [answeredCount]장째가 보상 지점인가 — 맞으면 그 지점(=지금까지 넘긴 장수), 아니면 null.
     *
     * 지점 값을 그대로 돌려주는 이유는 그것이 곧 **한 번뿐임을 보장하는 열쇠**이기 때문이다.
     * 20장째의 보상은 계정당 하나뿐이라, 카드를 고쳐 골라도 같은 지점을 다시 밟을 수 없다.
     */
    fun milestoneAt(answeredCount: Int): Int? =
        if (answeredCount > 0 && answeredCount % EVERY == 0) answeredCount else null
}
