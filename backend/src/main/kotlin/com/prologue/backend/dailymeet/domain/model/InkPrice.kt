package com.prologue.backend.dailymeet.domain.model

/**
 * 잉크 값표 — 무엇에 얼마가 드는지.
 *
 * 설정(yaml)이 아니라 코드에 두는 이유는 [InkProduct]와 같다. 돈이 걸린 값을 재배포 없이
 * 바꿀 수 있게 해두면 "편지 50"이 어느 날 조용히 80이 될 수 있고, 그 변화가 코드 리뷰에도
 * 남지 않는다. 값을 바꾸는 일은 눈에 보여야 한다.
 *
 * 한자리에 모아둔 이유는 따로 있다. 값들은 서로에 대해서만 의미가 있다 —
 * 편지 한 통이 프로필 열람 여섯 번어치라는 관계가 값 자체보다 중요하고,
 * 그 관계는 흩어놓으면 보이지 않는다.
 */
object InkPrice {
    /** 편지 한 통을 부치는 값. 연락처를 건네는 행동이라 가장 무겁다. */
    const val MAIL = 50

    /**
     * 서로 하트를 주고받은 상대에게 부치는 편지값 — [MAIL]의 30% 할인.
     *
     * 상호 하트는 뿌려서 만들 수 없는 신호(상대의 동의가 필요하다)라 파밍이 안 되고,
     * 마음이 통한 뒤의 편지는 먼저 다가가는 편지보다 가벼워야 "무료로도 이어질 수 있다"는
     * 희망이 선다. 다만 공짜로 두면 편지가 신중한 한 통이길 그만두므로 할인에서 멈춘다.
     */
    const val MAIL_MUTUAL = MAIL * 7 / 10

    /**
     * 받은 편지에 답장하는 값 — [MAIL]의 50% 할인.
     *
     * 상대는 이미 정가를 내고 연락처를 건넸다. 답장은 그 연결을 완성하는 마지막 한 걸음이라,
     * 여기서 값이 무거우면 편지 한 통이 닿고도 이어지지 못한다. 상호 하트 할인보다 깊은 이유는
     * 신호의 무게가 다르기 때문이다 — 하트는 마음이고, 편지는 값을 치른 마음이다.
     * 답장은 상호 하트 여부와 무관하게 이 값이다(둘 중 낮은 쪽).
     */
    const val MAIL_REPLY = MAIL / 2

    /** 사흘이 지나 닫힌 프로필을 다시 여는 값. 편지보다 훨씬 가볍게 둔다 — 보는 일과 건네는 일은 다르다. */
    const val PROFILE_UNLOCK = 8

    /**
     * 읽히지 않은 편지를 회수했을 때 돌아오는 잉크 — 부친 값의 절반.
     *
     * 전액이면 아무에게나 보내고 되거두는 게 공짜가 되어 편지가 신중한 한 통이길 그만두고,
     * 한 푼도 안 주면 상대가 읽지도 않은 값을 그대로 잃는다. 절반이 그 사이다.
     * 할인받아 부친 편지는 할인된 값의 절반이 돌아온다 — 낸 만큼에서 돌려준다.
     */
    fun recallRefund(paid: Int): Int = paid / 2

    /**
     * 오늘의 질문에 답을 남기면(하루 한 번) 고이는 잉크.
     *
     * 답변은 이 앱의 공급이라 보상해도 앱에 이롭고, 하루 한 문답이라 상한이 저절로 선다.
     * 한 달을 꾸준히 쓰면 편지 한 통어치가 모인다 — "돈을 안 내도 쓸 수 있다"는 약속의 실체다.
     */
    const val DAILY_ANSWER = 2

    /**
     * 지갑을 처음 열 때 주는 환영 잉크.
     *
     * 편지 한 통이 만원에 가까운 값이라 넉넉히 줄 수 없다. 다만 첫 한 통은 겪어봐야
     * 무엇을 사는 것인지 알 수 있어서, 지금은 딱 한 통어치를 준다.
     *
     * [MAIL]과 값은 같지만 묶어두지 않는다 — 편지값을 올리는 일과 환영 선물을 늘리는 일은
     * 서로 다른 판단이고, 묶어두면 한쪽을 손댈 때 다른 쪽이 조용히 따라 움직인다.
     */
    const val WELCOME = 50

    /**
     * 친구 초대 보상 — 초대한 쪽과 초대받은 쪽 모두에게.
     *
     * 소개팅은 친구가 친구를 데려오는 구조라 가장 값싼 유입이고, 초기에 사람을 모으는 일이
     * 무엇보다 급하다. 편지 두 통어치 — 초대가 정말 값진 기회라는 판단(2026-08-19)으로 넉넉히 둔다.
     * 대신 초대한 쪽은 [ReferralPolicy.MAX_REWARDED_INVITES]까지만 받아 가입을 찍어내 캐는 길을 막는다.
     * 운영자가 만드는 특별 코드는 이 값을 쓰지 않고 코드에 적힌 보상을 쓴다([InviteCode.inviteeReward]).
     */
    const val REFERRAL = 100
}
