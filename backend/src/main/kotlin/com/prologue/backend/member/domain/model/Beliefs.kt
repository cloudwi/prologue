package com.prologue.backend.member.domain.model

/**
 * 종교와 정치 성향 — **민감정보**(개인정보보호법 23조: 사상·신념, 정치적 견해, 종교적 신념).
 *
 * 소개팅에서 이 둘은 실제로 만남을 가르는 조건이라 묻지 않으면 프로필이 반쪽이 된다.
 * 그러나 법이 따로 다루는 정보이기도 해서, 이 앱에서는 세 가지를 지킨다.
 *
 * ① **전부 선택이다.** 안 고르면 null이고, 프로필에서 아예 보이지 않는다("무응답"조차 쓰지 않는다).
 * ② **적을 때 따로 동의를 받는다.** 가입 때 받은 민감정보 동의(선호 성별)와 별개의 항목이라
 *    같은 동의로 갈음하지 않는다 — 동의는 항목별로 받아야 한다(22조).
 * ③ **한 번 적어도 언제든 지운다.** 지우는 데는 동의가 필요 없다(처리정지·삭제권).
 *
 * 값 자체를 매칭 점수에 넣지는 않는다([PeerScore]). 이 둘은 "순서"의 문제가 아니라 "조건"의
 * 문제라, 넣는다면 점수가 아니라 자격([PeerEligibility])이고 그건 본인이 고른 선호여야 한다 —
 * 지금은 프로필에 보여주기만 한다.
 */
enum class Religion {
    /** 무교 — 종교가 없다는 것도 하나의 답이다. 밝히지 않는 것(null)과는 다르다. */
    NONE,
    CHRISTIAN,
    CATHOLIC,
    BUDDHIST,
    WON_BUDDHIST,
    ISLAM,
    OTHER,
}

/**
 * 정치 성향. 다섯 눈금과 "관심 없음" 하나.
 *
 * 눈금을 진보·중도·보수 셋으로만 두면 대부분이 중도로 몰려 아무것도 가르지 못하고,
 * 일곱으로 늘리면 자기 자리를 고르기 어려워진다. 관심 없음은 중도와 다른 답이라 따로 둔다.
 */
enum class PoliticalLeaning {
    PROGRESSIVE,
    CENTER_LEFT,
    CENTER,
    CENTER_RIGHT,
    CONSERVATIVE,
    APOLITICAL,
}
