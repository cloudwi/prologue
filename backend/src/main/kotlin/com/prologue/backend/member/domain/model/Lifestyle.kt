package com.prologue.backend.member.domain.model

/**
 * 생활 습관 — 프로필의 공통 질문 셋(흡연·음주·만나는 빈도).
 *
 * 종교·정치([Religion], [PoliticalLeaning])와 달리 민감정보가 아니라 별도 동의가 필요 없다.
 * 그러나 저장 경로는 같은 이유로 프로필 저장(전체 덮어쓰기)과 분리했다 — 이 항목을 모르는
 * 화면이 프로필을 한 번 저장할 때마다 조용히 지우는 일을 막기 위해서다.
 *
 * 셋 다 선택이고, 안 고르면 null이라 프로필에 아무것도 그리지 않는다. "무응답"은 답이 아니다.
 *
 * 왜 하필 이 셋인가: 소개팅에서 "만나기 전에 알았으면" 소리가 가장 많이 나오는 항목들이다.
 * 담배와 술은 함께 사는 시간의 모양을 바꾸고, 만나는 빈도는 연애의 속도를 정한다 —
 * 셋 다 나중에 알면 서로의 시간을 쓴 뒤가 된다.
 */
enum class Smoking {
    /** 안 피워요. */
    NONE,
    /** 끊는 중이에요. */
    QUITTING,
    /** 가끔 피워요. */
    SOMETIMES,
    /** 피워요. */
    REGULAR,
}

enum class Drinking {
    /** 안 마셔요. */
    NONE,
    /** 거의 안 마셔요. */
    RARELY,
    /** 가끔 마셔요. */
    SOMETIMES,
    /** 자주 마셔요. */
    OFTEN,
}

/**
 * 일주일에 몇 번쯤 만나고 싶은가.
 *
 * 숫자를 물으면 정확해 보이지만 아무도 지키지 못한다. 네 칸으로 나눈 건 "이 사람과 나의
 * 속도가 비슷한가"만 알면 충분해서다. 정하기 어려운 사람을 위해 [FLEXIBLE]을 둔다 —
 * 그것도 답이지 무응답이 아니다.
 */
enum class MeetFrequency {
    /** 주 1회쯤. */
    ONCE,
    /** 주 2~3회. */
    TWO_TO_THREE,
    /** 주 4회 이상. */
    FOUR_PLUS,
    /** 그때그때 달라요. */
    FLEXIBLE,
}
