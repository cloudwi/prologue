-- 취향 카드 — 둘 중 하나를 고르는 가벼운 문답.
--
-- 오늘의 질문(questions)과 **다른 더미**다. 로테이션에 섞지 않았다: 어떤 날은 탭 한 번으로 끝난다면
-- 다음 날 서술형 앞에서 사람은 "어제는 안 써도 됐는데"를 떠올리고, 그러면 읽을 글이 마른다.
-- 게다가 같은 날 모두가 같은 질문을 받는 게 소개의 전제라, 그날 질문이 객관식이면 옛 앱은 아무것도 못 한다.
--
-- 카드가 맡는 일은 셋이다.
--   ① 가입 직후의 백지를 없앤다 — 첫날 벽은 분량(10자)이 아니라 빈 화면이었다.
--   ② 매칭이 쓸 수 있는 **구조화된** 취향을 모은다(TasteAffinity → PeerScore 0.15).
--      서술형 답은 사람을 알게 하지만 계산되지 않는다. 카드는 그 반대다.
--   ③ 고른 뒤의 한 줄(note)로 쓰는 일까지 데려간다 — 고르고 난 자리의 한 줄은 백지의 한 줄보다 쉽다.
--
-- 잉크는 주지 않는다. 잉크는 이 앱의 공급(서술형 답)에 대한 보상이라, 탭 한 번에 고이면 아무도 쓰지 않는다.
create table taste_cards
(
    id       bigint      primary key,
    prompt   varchar(100) not null,
    option_a varchar(60)  not null,
    option_b varchar(60)  not null
);

comment on table taste_cards is '둘 중 하나를 고르는 취향 카드. 날짜와 무관한 더미 — 오늘의 질문과 섞지 않는다';

create table taste_choices
(
    account_id uuid        not null,
    card_id    bigint      not null,
    choice     varchar(1)  not null,
    -- 선택지 뒤에 덧붙이는 한 줄. 비어도 된다 — 강제하면 백지가 작아졌을 뿐 그대로다.
    note       varchar(100),
    created_at timestamptz not null default now(),
    primary key (account_id, card_id),
    constraint ck_taste_choice check (choice in ('A', 'B'))
);

-- 후보 전원의 취향을 한 번에 읽는다(PeerMatchingService) — 계정 묶음 조회가 매칭마다 돈다.
create index idx_taste_choices_account on taste_choices (account_id);

