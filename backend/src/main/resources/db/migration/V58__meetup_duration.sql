-- 모임이 몇 시에 끝나는지.
--
-- 그동안 meet_at 하나뿐이라 "저녁 6시"까지만 말할 수 있었다. 처음 가는 자리에서 가장 먼저
-- 계산하는 것이 "몇 시에 끝나지"인데, 그걸 모르면 약속을 못 잡아 신청을 미룬다.
--
-- 종료 시각(ends_at)이 아니라 소요 시간을 담는 이유:
-- 모임장은 "두 시간"으로 생각하지 "여덟 시"로 생각하지 않는다. 날짜·시간을 두 번 받으면
-- 그만큼 틀릴 자리가 늘고, 종료가 시작보다 앞선 모임이라는 있을 수 없는 상태가 생긴다.
-- 자정을 넘기는 모임도 계산이 알아서 처리한다. 보여줄 때 "오후 6시 – 8시"로 더하면 된다.
--
-- null은 "정하지 않음" — 지금까지 열린 모임은 그대로 시작 시각만 보인다.
alter table meetups add column duration_minutes int;

comment on column meetups.duration_minutes is '모임 소요 시간(분). null이면 정하지 않음 — 시작 시각만 보여준다';
