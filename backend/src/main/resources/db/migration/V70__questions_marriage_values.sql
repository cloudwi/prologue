-- 질문 풀을 연애·결혼 가치관으로 다시 짠다 (100 → 1,000).
--
-- **왜**: 문답은 이 앱의 첫 글이다 — 사진보다 답이 먼저 읽힌다. 그런데 기존 풀은
-- 일상·취향이 절반을 넘어서, 답을 다 읽어도 그 사람과 살아갈 수 있을지가 보이지 않았다.
-- 결혼을 염두에 둔 만남을 돕겠다면 질문이 먼저 그 자리로 가야 한다.
--
-- **무엇을**: 기존 100개를 전수 조사해 26개는 그대로 두고, 19개는 연애·결혼 쪽으로 문구를
-- 고쳤고, 55개는 통째로 갈아 끼웠다. 그 위에 900개를 새로 얹어 1,000개가 된다.
--
-- **삭제 대신 덮어쓰기**: answers.question_id가 questions를 참조하고, 어드민에도 삭제가 없다
-- (AdminQuestionController). 그래서 버릴 질문은 지우지 않고 그 자리에 새 질문을 쓴다 —
-- 답변 기록은 남고, 사라지는 건 문구뿐이다.
--
-- **순서가 곧 날짜다**: QuestionRotation은 epochDay % 풀 크기로 오늘의 질문을 고른다.
-- 그래서 id 순서는 곧 날짜 순서이고, 같은 주제가 연달아 오면 며칠째 같은 이야기를 쓰게 된다.
-- 101~1000은 20개 주제(끌림·표현·신뢰·갈등·소통·거리·시간·다정함·결혼관·결혼준비·결혼생활·
-- 지속·돈·집안일·일·생활습관·양가·자녀·건강·회복)를 한 칸씩 돌려 담았다 — 이웃한 날은
-- 절대 같은 주제가 아니다.
--
-- 풀이 100 → 1,000이 되면서 오늘의 질문이 한 번 건너뛴다(순환 주기 100일 → 1,000일).
-- 이미 남긴 답변은 질문 id에 붙어 있으므로 영향이 없다.

